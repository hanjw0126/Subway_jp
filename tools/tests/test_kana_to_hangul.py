import pytest

from kana_to_hangul import convert, resolve_ko

CASES = [
    ("しぶや", "시부야"), ("おもてさんどう", "오모테산도"), ("あおやまいっちょうめ", "아오야마잇초메"),
    ("あかさかみつけ", "아카사카미쓰케"), ("ためいけさんのう", "다메이케산노"), ("しんばし", "신바시"),
    ("きょうばし", "교바시"), ("にほんばし", "니혼바시"), ("すえひろちょう", "스에히로초"),
    ("うえのひろこうじ", "우에노히로코지"), ("おぎくぼ", "오기쿠보"), ("しんこうえんじ", "신코엔지"),
    ("なかのさかうえ", "나카노사카우에"), ("しんじゅくぎょえんまえ", "신주쿠교엔마에"), ("よつやさんちょうめ", "요쓰야산초메"),
    ("こっかいぎじどうまえ", "곳카이기지도마에"), ("とうきょう", "도쿄"), ("おおてまち", "오테마치"),
    ("おちゃのみず", "오차노미즈"), ("みょうがだに", "묘가다니"), ("しんおおつか", "신오쓰카"),
    ("すいてんぐうまえ", "스이텐구마에"), ("しんおおさか", "신오사카"), ("どうぶつえんまえ", "도부쓰엔마에"),
    ("てんのうじ", "덴노지"), ("コスモスクエア", "고스모스쿠에아"),
]


@pytest.mark.parametrize("kana,expected", CASES)
def test_convert(kana, expected):
    assert convert(kana) == expected


def test_override_priority():
    ov = {"広尾": "히로오"}
    assert convert("ひろお") == "히로"
    assert resolve_ko("広尾", "ひろお", ov) == "히로오"
    assert resolve_ko("渋谷", "しぶや", ov, given="시부야역") == "시부야역"
    assert resolve_ko("渋谷", "しぶや", ov) == "시부야"
